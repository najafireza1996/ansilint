//! Generators for parity and rule-documentation tables.

use std::fmt::Write as _;
use std::fs;

use anyhow::{Context, Result};

use crate::workspace::{display_relative, root};

struct ParityRow {
    id: String,
    status: String,
    phase: String,
    notes: String,
}

pub(crate) fn gen_parity() -> Result<()> {
    let workspace_root = root();
    let path = workspace_root.join("parity.toml");
    let text =
        fs::read_to_string(&path).with_context(|| format!("failed to read {}", path.display()))?;
    let parity: toml::Value =
        toml::from_str(&text).with_context(|| format!("failed to parse {}", path.display()))?;
    let (rows, implemented, total) = parity_rows(&parity);
    let output = render_parity(&rows, implemented, total);
    let target = workspace_root.join("docs/PARITY.md");
    fs::write(&target, output).with_context(|| format!("failed to write {}", target.display()))?;
    println!(
        "wrote {} ({implemented}/{total} implemented)",
        display_relative(&workspace_root, &target)
    );
    Ok(())
}

fn parity_rows(parity: &toml::Value) -> (Vec<ParityRow>, usize, usize) {
    let mut rows = Vec::new();
    let mut implemented = 0_usize;
    let mut total = 0_usize;
    if let Some(rules) = parity.get("rules").and_then(toml::Value::as_table) {
        for (id, spec) in rules {
            total += 1;
            let status = spec
                .get("status")
                .and_then(toml::Value::as_str)
                .unwrap_or("planned");
            if status == "implemented" {
                implemented += 1;
            }
            rows.push(ParityRow {
                id: id.clone(),
                status: status.to_string(),
                phase: spec
                    .get("phase")
                    .and_then(toml::Value::as_integer)
                    .map_or_else(|| "-".to_string(), |phase| phase.to_string()),
                notes: spec
                    .get("notes")
                    .and_then(toml::Value::as_str)
                    .unwrap_or("")
                    .to_string(),
            });
        }
    }
    rows.sort_by(|left, right| left.id.cmp(&right.id));
    (rows, implemented, total)
}

fn render_parity(rows: &[ParityRow], implemented: usize, total: usize) -> String {
    let percentage = (implemented * 100).checked_div(total).unwrap_or(0);
    let mut output = String::from(
        "# Rule parity\n\nGenerated by `cargo xtask gen-parity`. Do not edit by hand.\n\n",
    );
    let _ = writeln!(
        output,
        "Implemented: {implemented}/{total} ({percentage}%)\n"
    );
    output.push_str("| Rule | Status | Phase | Notes |\n|---|---|---|---|\n");
    for row in rows {
        let ParityRow {
            id,
            status,
            phase,
            notes,
        } = row;
        let _ = writeln!(output, "| `{id}` | {status} | {phase} | {notes} |");
    }
    output
}

pub(crate) fn gen_rule_docs() -> Result<()> {
    let workspace_root = root();
    let rules_dir = workspace_root.join("crates/ansilint-rules/src/rules");
    let mut ids = Vec::new();
    if rules_dir.is_dir() {
        for entry in fs::read_dir(&rules_dir)
            .with_context(|| format!("failed to read {}", rules_dir.display()))?
        {
            let path = entry?.path();
            if path.extension().is_some_and(|extension| extension == "rs") {
                if let Some(stem) = path.file_stem().and_then(std::ffi::OsStr::to_str) {
                    if stem != "mod" {
                        ids.push(stem.to_string());
                    }
                }
            }
        }
    }
    ids.sort();

    let mut output = String::from(
        "# Rules\n\nGenerated by `cargo xtask gen-rule-docs`. Do not edit by hand.\n\n",
    );
    if ids.is_empty() {
        output.push_str("No rules are implemented yet.\n");
    } else {
        output.push_str("| Rule | Documentation |\n|---|---|\n");
        for id in &ids {
            let _ = writeln!(output, "| `{id}` | [{id}]({id}.md) |");
        }
    }
    let target = workspace_root.join("docs/rules/README.md");
    fs::write(&target, output).with_context(|| format!("failed to write {}", target.display()))?;
    println!("wrote docs/rules/README.md ({} rule(s))", ids.len());
    Ok(())
}

